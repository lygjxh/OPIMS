// extractCountry 依次匹配 countryRules，返回首个命中的国别；无命中返回"其他"。
func extractCountry(name, addr string) string {
	text := name + addr
	for _, r := range countryRules {
		if strings.Contains(text, r.Keyword) {
			return r.Country
		}
	}
	return "其他"
}
