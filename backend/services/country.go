package services

import "strings"

// countryRule 将项目名称/地址中的关键词映射到国别。
// 用切片而非 map，保证匹配顺序确定（Go 的 map 遍历顺序是随机的，
// 若项目名同时含多个关键词，用 map 会导致结果在多次运行间跳变）。
// 顺序原则：越具体的关键词排在越前面，通用缩写排最后。
type countryRule struct {
	Keyword string
	Country string
}

