/** 同一国别多个项目时的散开偏移（避免标记完全重叠） */
export function spreadOffset(index: number): [number, number] {
  if (index === 0) return [0, 0]
  const ring = Math.ceil(Math.sqrt(index + 1)) - 1
  const angle = (index * 137.5 * Math.PI) / 180 // 黄金角，分布更均匀
  const r = 1.1 + ring * 0.9
  return [Math.sin(angle) * r, Math.cos(angle) * r]
}
